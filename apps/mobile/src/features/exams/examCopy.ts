export const EXAM_COPY: Record<AuthLanguage, ExamCopy> = { zh: ZH, en: EN, fr: FR };

/** Maps a backend error code (ApiClientError.message) to a sentence. */
export function describeExamError(error: unknown, copy: ExamCopy): string {
  const code = error instanceof Error ? error.message : "";
  return copy.errors[code] ?? copy.errors.fallback;
}
